        with st.spinner("Writing SQL…"):
            sql, source = explain.to_sql(question)
        if sql is None:
            st.warning(source)
        else:
            with st.expander("SQL", expanded=True):
                st.code(sql, language="sql")
            error = explain.check_read_only(sql)
            if error:
                st.error(error)
            else:
                try:
                    result = q(f"SELECT * FROM ({sql}) LIMIT 500")
                    ui.table(result)
                    st.caption(f"{len(result):,} rows · SQL from {source}")
                except Exception as e:
                    st.error(f"Query failed: {e}")
