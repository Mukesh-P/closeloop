SERIES = "#2a78d6"


@st.cache_resource
def _cached_conn():
    return connect()


def get_conn():
    """Shared connection; reconnects transparently if Exasol dropped it."""
    conn = _cached_conn()
    if conn.is_closed:
        _cached_conn.clear()
        conn = _cached_conn()
    return conn


def q(sql, params=None):
    try:
        return query_df(get_conn(), sql, params)
    except (pyexasol.ExaCommunicationError, pyexasol.ExaRuntimeError):
        _cached_conn.clear()
        return query_df(get_conn(), sql, params)


def crore(x):
    return f"₹{float(x or 0) / 1e7:,.1f} Cr"


def csv(df):
    return df.to_csv(index=False).encode()


def show_explanation(finding, key):
    if st.button("Explain", key=f"explain-{key}", type="primary"):
        with st.spinner("Writing explanation…"):
            text, source = explain.explain(finding)
        st.markdown(text)
        st.caption(f"Generated by {source}")


