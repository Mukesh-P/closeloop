# ---------------------------------------------------------------- Ask
with tabs[5]:
    st.caption("Ask a question in plain English. CloseLoop writes the SQL, checks it is read-only, and runs it on Exasol.")
    preset = st.selectbox("Pick a question", ["(type your own below)"] + list(explain.PRESET_QUESTIONS))
    free = st.text_input("…or ask your own", placeholder="e.g. Which currency has the most FX breaks?",
                         disabled=not explain.has_claude(),
                         help=None if explain.has_claude() else "Set ANTHROPIC_API_KEY to enable free-form questions")
    question = free.strip() or (preset if preset in explain.PRESET_QUESTIONS else "")
    if question:
        with st.spinner("Writing SQL…"):
            sql, source = explain.to_sql(question)
        if sql is None:
            st.warning(source)
        else:
            st.code(sql, language="sql")
            error = explain.check_read_only(sql)
            if error:
                st.error(error)
            else:
                try:
                    result = q(f"SELECT * FROM ({sql}) LIMIT 500")
                    st.dataframe(result, hide_index=True, width="stretch")
                    st.caption(f"{len(result):,} rows · SQL from {source}")
                except Exception as e:
                    st.error(f"Query failed: {e}")
