@st.cache_resource
def _cached_conn():
    return connect()


def get_conn():
    """Shared connection; reconnects transparently if Exasol dropped it."""
    conn = _cached_conn()
    if conn.is_closed:
        _cached_conn.clear()
        conn = _cached_conn()
    return conn


def q(sql, params=None):
    try:
        return query_df(get_conn(), sql, params)
    except (pyexasol.ExaCommunicationError, pyexasol.ExaRuntimeError):
        _cached_conn.clear()
        return query_df(get_conn(), sql, params)


def crore(x):
    return f"₹{float(x or 0) / 1e7:,.1f} Cr"


def csv(df):
    return df.to_csv(index=False).encode()


def short_step(label):
    """'Pass 3: FX / rounding within tolerance (any timing)' -> 'FX / rounding'."""
    name = label.split(":", 1)[1] if label.startswith("Pass") else label
    name = re.split(r"\(| within| with| across| on true|:", name)[0].strip()
    return name[0].upper() + name[1:]


def show_explanation(finding, key):
    if st.button("✨ Explain", key=f"explain-{key}", type="primary"):
        with st.spinner("Writing explanation…"):
            text, source = explain.explain(finding)
        with st.container(border=True):
            st.markdown(text)
            st.caption(f"Generated by {source}")


