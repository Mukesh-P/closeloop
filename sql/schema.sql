-- Source system tables (loaded by `python -m closeloop.load`)

CREATE OR REPLACE TABLE CORE_TXN (
    TXN_ID          VARCHAR(20)   NOT NULL,
    REFERENCE       VARCHAR(40)   NOT NULL,
    ACCOUNT_ID      VARCHAR(12)   NOT NULL,
    VALUE_DATE      DATE          NOT NULL,
    AMOUNT          DECIMAL(18,2) NOT NULL,
    CURRENCY        CHAR(3)       NOT NULL,
    COUNTERPARTY_ID DECIMAL(9,0)
);

CREATE OR REPLACE TABLE GL_ENTRY (
    GL_ID      VARCHAR(20)   NOT NULL,
    REFERENCE  VARCHAR(40)   NOT NULL,
    ACCOUNT_ID VARCHAR(12)   NOT NULL,
    POST_DATE  DATE          NOT NULL,
    AMOUNT     DECIMAL(18,2) NOT NULL,
    CURRENCY   CHAR(3)       NOT NULL
);

-- Hidden answer key for planted breaks, only used to score the engine
CREATE OR REPLACE TABLE GROUND_TRUTH (
    RECORD_ID VARCHAR(20) NOT NULL,
    SIDE      VARCHAR(4)  NOT NULL,
    TRUE_TYPE VARCHAR(20) NOT NULL
);

CREATE OR REPLACE TABLE LOAN_BOOK (
    FACILITY_ID     VARCHAR(12)   NOT NULL,
    BORROWER_CODE   VARCHAR(10)   NOT NULL,
    BORROWER_NAME   VARCHAR(200)  NOT NULL,
    OUTSTANDING_INR DECIMAL(18,2) NOT NULL
);

CREATE OR REPLACE TABLE TREASURY (
    TRADE_ID         VARCHAR(12)   NOT NULL,
    CPTY_NAME        VARCHAR(200)  NOT NULL,
    PRODUCT          VARCHAR(10)   NOT NULL,
    MTM_EXPOSURE_INR DECIMAL(18,2) NOT NULL
);

CREATE OR REPLACE TABLE RISK_LIMITS (
    RISK_ID               VARCHAR(10)   NOT NULL,
    LEGAL_NAME            VARCHAR(200)  NOT NULL,
    APPROVED_LIMIT_INR    DECIMAL(18,2) NOT NULL,
    REPORTED_EXPOSURE_INR DECIMAL(18,2) NOT NULL
);

CREATE OR REPLACE TABLE APPLICATIONS (
    APP_ID         VARCHAR(10)   NOT NULL,
    APPLICANT_NAME VARCHAR(200)  NOT NULL,
    PRODUCT        VARCHAR(20)   NOT NULL,
    REQUESTED_INR  DECIMAL(18,2) NOT NULL
);

-- Analyst decisions on breaks (maker-checker audit trail)
CREATE OR REPLACE TABLE BREAK_REVIEW (
    BREAK_KEY  VARCHAR(50)  NOT NULL,
    DECISION   VARCHAR(20)  NOT NULL,
    NOTE       VARCHAR(500),
    DECIDED_BY VARCHAR(100),
    DECIDED_AT TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- Results of a previous close are stale once source data is reloaded
DROP TABLE IF EXISTS CLOSE_RUN_STEPS;
DROP TABLE IF EXISTS RECON_MATCH;
DROP TABLE IF EXISTS GL_RANKED;
DROP TABLE IF EXISTS BREAKS;
DROP TABLE IF EXISTS PROPOSED_JOURNALS;
DROP TABLE IF EXISTS ENTITY_EXPOSURE;
DROP TABLE IF EXISTS CREDIT_DECISIONS;
