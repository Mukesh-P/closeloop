"""Credit decisions on new applications, made on true cross-system exposure.

Compares what the bank would decide using the risk system alone (LEGACY_DECISION)
with the decision on reconciled exposure, and records a reason code and a
counter-offer so a decline can be explained to the customer.
"""
import time

from closeloop.db import query_df

BUILD = """
CREATE OR REPLACE TABLE CREDIT_DECISIONS AS
WITH a AS (SELECT APP_ID, APPLICANT_NAME, PRODUCT, REQUESTED_INR,
                  NORMALIZE_NAME(APPLICANT_NAME) AS ENTITY_KEY FROM APPLICATIONS),
d AS (
    SELECT a.APP_ID, a.APPLICANT_NAME, a.PRODUCT, a.REQUESTED_INR,
           e.RISK_ID, e.LEGAL_NAME, e.APPROVED_LIMIT_INR, e.REPORTED_EXPOSURE_INR, e.TRUE_EXPOSURE_INR,
           e.NAME_VARIANTS,
           GREATEST(e.APPROVED_LIMIT_INR - e.TRUE_EXPOSURE_INR, 0) AS HEADROOM_INR,
           (e.TRUE_EXPOSURE_INR + a.REQUESTED_INR) / e.APPROVED_LIMIT_INR AS UTIL_AFTER,
           CASE WHEN e.REPORTED_EXPOSURE_INR + a.REQUESTED_INR <= e.APPROVED_LIMIT_INR
                THEN 'APPROVE' ELSE 'DECLINE' END AS LEGACY_DECISION,
           CASE WHEN e.RISK_ID IS NULL THEN 'REFER'
                WHEN e.TRUE_EXPOSURE_INR + a.REQUESTED_INR <= e.APPROVED_LIMIT_INR THEN 'APPROVE'
                ELSE 'DECLINE' END AS DECISION,
           CASE WHEN e.RISK_ID IS NULL THEN 'NO_CREDIT_RECORD'
                WHEN e.TRUE_EXPOSURE_INR > e.APPROVED_LIMIT_INR THEN 'EXISTING_EXPOSURE_ABOVE_LIMIT'
                WHEN e.TRUE_EXPOSURE_INR + a.REQUESTED_INR > e.APPROVED_LIMIT_INR THEN 'INSUFFICIENT_HEADROOM'
           END AS REASON_CODE
    FROM a LEFT JOIN ENTITY_EXPOSURE e ON e.ENTITY_KEY = a.ENTITY_KEY
)
SELECT d.*,
       CASE WHEN DECISION = 'DECLINE' AND HEADROOM_INR >= 100000
            THEN FLOOR(HEADROOM_INR / 100000) * 100000 END AS COUNTER_OFFER_INR,
       CASE WHEN LEGACY_DECISION = 'APPROVE' AND DECISION = 'DECLINE' THEN TRUE ELSE FALSE END AS PREVENTED_BAD_APPROVAL
FROM d
"""


def run(conn):
    t = time.time()
    conn.execute(BUILD)
    return time.time() - t


def summary(conn):
    return query_df(conn, """
        SELECT DECISION, REASON_CODE, COUNT(*) AS APPLICATIONS, SUM(REQUESTED_INR) AS REQUESTED_INR,
               SUM(CASE WHEN PREVENTED_BAD_APPROVAL THEN 1 ELSE 0 END) AS LEGACY_WOULD_APPROVE
        FROM CREDIT_DECISIONS GROUP BY DECISION, REASON_CODE ORDER BY APPLICATIONS DESC""")
