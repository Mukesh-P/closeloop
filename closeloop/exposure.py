"""Unified counterparty exposure across LOAN_BOOK, TREASURY and RISK_LIMITS.

The three systems share no common key and spell names differently, so entities
are resolved with the NORMALIZE_NAME Python UDF running inside Exasol.
"""
import time

from closeloop.db import query_df

BUILD = """
CREATE OR REPLACE TABLE ENTITY_EXPOSURE AS
WITH loans AS (
    SELECT NORMALIZE_NAME(BORROWER_NAME) AS ENTITY_KEY,
           SUM(OUTSTANDING_INR) AS LOANS_INR,
           COUNT(*) AS FACILITIES,
           COUNT(DISTINCT BORROWER_NAME) AS LOAN_NAME_VARIANTS
    FROM LOAN_BOOK GROUP BY 1
), trades AS (
    SELECT NORMALIZE_NAME(CPTY_NAME) AS ENTITY_KEY,
           SUM(MTM_EXPOSURE_INR) AS TREASURY_INR,
           COUNT(*) AS TRADES,
           COUNT(DISTINCT CPTY_NAME) AS TRADE_NAME_VARIANTS
    FROM TREASURY GROUP BY 1
), risk AS (
    SELECT NORMALIZE_NAME(LEGAL_NAME) AS ENTITY_KEY, RISK_ID, LEGAL_NAME,
           APPROVED_LIMIT_INR, REPORTED_EXPOSURE_INR
    FROM RISK_LIMITS
)
SELECT r.RISK_ID, r.LEGAL_NAME, r.ENTITY_KEY,
       r.APPROVED_LIMIT_INR,
       r.REPORTED_EXPOSURE_INR,
       COALESCE(l.LOANS_INR, 0) AS LOANS_INR,
       COALESCE(t.TREASURY_INR, 0) AS TREASURY_INR,
       COALESCE(l.LOANS_INR, 0) + COALESCE(t.TREASURY_INR, 0) AS TRUE_EXPOSURE_INR,
       COALESCE(l.FACILITIES, 0) AS FACILITIES,
       COALESCE(t.TRADES, 0) AS TRADES,
       COALESCE(l.LOAN_NAME_VARIANTS, 0) + COALESCE(t.TRADE_NAME_VARIANTS, 0) + 1 AS NAME_VARIANTS,
       r.REPORTED_EXPOSURE_INR / r.APPROVED_LIMIT_INR AS REPORTED_UTIL,
       (COALESCE(l.LOANS_INR, 0) + COALESCE(t.TREASURY_INR, 0)) / r.APPROVED_LIMIT_INR AS TRUE_UTIL,
       CASE
         WHEN COALESCE(l.LOANS_INR, 0) + COALESCE(t.TREASURY_INR, 0) > r.APPROVED_LIMIT_INR
              AND r.REPORTED_EXPOSURE_INR <= r.APPROVED_LIMIT_INR THEN 'HIDDEN_BREACH'
         WHEN COALESCE(l.LOANS_INR, 0) + COALESCE(t.TREASURY_INR, 0) > r.APPROVED_LIMIT_INR THEN 'KNOWN_BREACH'
         WHEN (COALESCE(l.LOANS_INR, 0) + COALESCE(t.TREASURY_INR, 0)) > 0.9 * r.APPROVED_LIMIT_INR THEN 'NEAR_LIMIT'
         ELSE 'OK' END AS STATUS
FROM risk r
LEFT JOIN loans l ON l.ENTITY_KEY = r.ENTITY_KEY
LEFT JOIN trades t ON t.ENTITY_KEY = r.ENTITY_KEY
"""

UNRESOLVED = """
SELECT 'LOAN_BOOK' AS SOURCE_SYSTEM, COUNT(DISTINCT NORMALIZE_NAME(BORROWER_NAME)) AS ENTITIES
FROM LOAN_BOOK WHERE NORMALIZE_NAME(BORROWER_NAME) NOT IN (SELECT ENTITY_KEY FROM ENTITY_EXPOSURE)
UNION ALL
SELECT 'TREASURY', COUNT(DISTINCT NORMALIZE_NAME(CPTY_NAME))
FROM TREASURY WHERE NORMALIZE_NAME(CPTY_NAME) NOT IN (SELECT ENTITY_KEY FROM ENTITY_EXPOSURE)
"""


def run(conn):
    t = time.time()
    conn.execute(BUILD)
    return time.time() - t


def status_counts(conn):
    return query_df(conn, """
        SELECT STATUS, COUNT(*) AS COUNTERPARTIES,
               SUM(TRUE_EXPOSURE_INR - REPORTED_EXPOSURE_INR) AS UNREPORTED_INR
        FROM ENTITY_EXPOSURE GROUP BY STATUS ORDER BY 2 DESC""")


def unresolved(conn):
    return query_df(conn, UNRESOLVED)
